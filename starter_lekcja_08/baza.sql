-- Tabele aplikacji (stan po lekcji 7): pamięć z lekcji 5, baza wiedzy z lekcji 6
-- i prywatne dane każdego konta z lekcji 7.
-- Jak użyć: Supabase → SQL Editor → wklej całą zawartość tego pliku → Run.
-- Skrypt jest bezpieczny do ponownego uruchomienia: tworzy tylko to, czego brakuje,
-- istniejących tabel i danych nie rusza.

-- ---------- Lekcja 5: rozmowy i profil ----------

-- Lista rozmów: jeden wiersz = jedna rozmowa.
create table if not exists public.conversations (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  title text
);

-- Wiadomości: każda należy do jednej rozmowy (conversation_id).
-- Usunięcie rozmowy usuwa też jej wiadomości (on delete cascade).
create table if not exists public.messages (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  conversation_id bigint not null references public.conversations (id) on delete cascade,
  role text,
  content text
);

-- Profil użytkownika: imię i pozostałe fakty (preferences). Jeden wiersz na osobę (patrz lekcja 7 niżej).
create table if not exists public.user_profiles (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  name text,
  preferences jsonb
);

-- RLS włączony: nikt z internetu nie przeczyta tych tabel.
-- Polityki „tylko własne wiersze” dochodzą w części „Lekcja 7” na końcu pliku.
alter table public.conversations enable row level security;
alter table public.messages enable row level security;
alter table public.user_profiles enable row level security;

-- Pełny dostęp ma serwer aplikacji, gdy łączy się kluczem secret (rola service_role).
grant all on table public.conversations to service_role;
grant all on table public.messages to service_role;
grant all on table public.user_profiles to service_role;

-- ---------- Lekcja 6: baza wiedzy (RAG) ----------

-- Dodatek pgvector: nowy typ kolumny "vector" i wyszukiwanie po znaczeniu.
-- To samo, co przełącznik w Supabase → Database → Extensions → vector.
create extension if not exists vector with schema extensions;

-- Lista dokumentów: tytuł i data dodania.
create table if not exists public.documents (
  id bigint generated always as identity primary key,
  title text not null,
  created_at timestamptz not null default now()
);

-- Fragmenty dokumentów: każdy należy do jednego dokumentu (document_id).
-- Usunięcie dokumentu usuwa też jego fragmenty (on delete cascade).
-- Kolumna embedding to lista 1536 liczb opisująca znaczenie fragmentu.
-- 1536 to długość embeddingu modelu openai/text-embedding-3-small. Przy innym modelu
-- zmień tę liczbę tutaj i w funkcji match_chunks niżej.
create table if not exists public.chunks (
  id bigint generated always as identity primary key,
  document_id bigint not null references public.documents (id) on delete cascade,
  chunk_index int not null,
  content text not null,
  embedding extensions.vector(1536)
);

-- RLS włączony i żadnych polityk: baza wiedzy jest wspólna i czyta ją tylko serwer kluczem secret.
alter table public.documents enable row level security;
alter table public.chunks enable row level security;

-- Dostęp ma tylko serwer aplikacji (rola service_role).
grant all on table public.documents to service_role;
grant all on table public.chunks to service_role;

-- Wyszukiwanie po znaczeniu: dostaje embedding pytania i zwraca najbliższe fragmenty
-- (domyślnie 3) razem z tytułem dokumentu. Podobieństwo: im bliżej 1, tym bliższe znaczenie.
create or replace function public.match_chunks (
  query_embedding extensions.vector(1536),
  match_count int default 3
)
returns table (id bigint, document_id bigint, title text, content text, similarity float)
language sql stable
set search_path = public, extensions
as $$
  select c.id, c.document_id, d.title, c.content,
         1 - (c.embedding <=> query_embedding) as similarity
  from chunks c
  join documents d on d.id = c.document_id
  order by c.embedding <=> query_embedding
  limit match_count;
$$;

-- Funkcję może wywołać tylko serwer aplikacji.
grant execute on function public.match_chunks to service_role;

-- ---------- Lekcja 7: konta użytkowników i prywatne dane (RLS) ----------

-- Rozmowy, wiadomości i profil należą do zalogowanej osoby. Aplikacja czyta je i zapisuje
-- jako ta osoba (klucz publishable + sesja), a baza oddaje jej tylko własne wiersze.
-- Wiersze sprzed lekcji 7 mają puste user_id — nie należą do nikogo i nikt ich nie zobaczy.

-- 1. Każdy wiersz dostaje właściciela. Baza wpisuje go sama: to zalogowana osoba.
alter table public.conversations
  add column if not exists user_id uuid default auth.uid() references auth.users (id) on delete cascade;
alter table public.messages
  add column if not exists user_id uuid default auth.uid() references auth.users (id) on delete cascade;
alter table public.user_profiles
  add column if not exists user_id uuid default auth.uid() references auth.users (id) on delete cascade;

-- 2. Jedna osoba ma jeden profil.
create unique index if not exists user_profiles_user_id_key on public.user_profiles (user_id);

-- 3. RLS zostaje włączony.
alter table public.conversations enable row level security;
alter table public.messages enable row level security;
alter table public.user_profiles enable row level security;

-- 4. Polityki: zalogowana osoba czyta, dodaje, zmienia i usuwa tylko swoje wiersze.
drop policy if exists "tylko wlasne rozmowy" on public.conversations;
create policy "tylko wlasne rozmowy" on public.conversations
  for all to authenticated
  using ((select auth.uid()) = user_id)
  with check ((select auth.uid()) = user_id);

drop policy if exists "tylko wlasne wiadomosci" on public.messages;
create policy "tylko wlasne wiadomosci" on public.messages
  for all to authenticated
  using ((select auth.uid()) = user_id)
  with check ((select auth.uid()) = user_id);

drop policy if exists "tylko wlasny profil" on public.user_profiles;
create policy "tylko wlasny profil" on public.user_profiles
  for all to authenticated
  using ((select auth.uid()) = user_id)
  with check ((select auth.uid()) = user_id);

-- 5. Zalogowane osoby mogą korzystać z tych tabel (w granicach polityk).
grant select, insert, update, delete
  on table public.conversations, public.messages, public.user_profiles
  to authenticated;
